def recorded_path(repo: Path, path: str) -> Path:
    """A path a frozen manifest recorded: as written, or under its bucket after the move."""
    written = repo / path
    if written.exists() or not path.startswith("config/"):
        return written
    rest = path.removeprefix("config/")
    top = rest.split("/")[0]
    bucket = "runs" if top.startswith("aparinds-") else CONFIG_PREFIXES[top]
    return repo / "config" / bucket / rest


def old_package_files(package: str) -> list[Path]:
    """The source files of the modules an old package held."""
    repo = Path(__file__).resolve().parents[3]
    return [repo / (name.replace(".", "/") + ".py") for name in OLD_PACKAGES[package]]
