def dotted(path: str) -> str:
    """The module name of a Python path under a source root."""
    return path.removeprefix("src/").removesuffix(".py").removesuffix("/__init__").replace("/", ".")


MOD = {dotted(row["old"]): dotted(row["new"]) for row in MOVES if row["kind"] == "module"}
PACKAGES = {dotted(row["old"]) for row in MOVES if row["kind"] == "init"}
KEPT_PACKAGES = {
    dotted(row["old"]): dotted(row["new"])
    for row in MOVES
    if row["kind"] == "init" and not row["new"].startswith("(")
}
NEW_MODULES = set(MOD.values()) | set(KEPT_PACKAGES.values())
PREFIX = {}
for old_path, new_path in CONF.items():
    rel = old_path.removeprefix("config/")
    top = rel.split("/")[0]
    PREFIX[top] = new_path.removeprefix("config/").removesuffix(rel).strip("/")
NEW_TOPS = {prefix.split("/")[0] for prefix in PREFIX.values()}


def config_prefix(top: str) -> str | None:
    """The bucket a first config segment (or a run-config name prefix) moved under."""
    return PREFIX.get(top) or ("runs" if top.startswith("aparinds-") else None)


def config_relative(text: str) -> bool:
    """A run config's name or a config folder's YAML path, which no ``config/`` prefix marks."""
    top = text.split("/")[0]
    return text.endswith(".yaml") and (top.startswith("aparinds-") or "/" in text and top in PREFIX)


def map_module_text(match: re.Match[str], strict: bool, where: str) -> str:
    """A dotted name through the map, longest module prefix first, keeping an attribute suffix."""
    text = match.group()
    parts = text.split(".")
    for end in range(len(parts), 1, -1):
        name = ".".join(parts[:end])
        if name in MOD:
            return ".".join([MOD[name], *parts[end:]])
    if strict and any(".".join(parts[:end]) in PACKAGES for end in range(2, len(parts) + 1)):
        problems.append(f"{where}: names an old package with no row: {text}")
    return text


def map_src_text(match: re.Match[str], strict: bool, where: str) -> str:
    """A src/fundamentals path through the map."""
    text = match.group()
    if text in MOVED:
        return MOVED[text]
    if strict:
        problems.append(f"{where}: unmapped source path: {text}")
    return text


def map_test_text(match: re.Match[str], strict: bool, where: str) -> str:
    """A tests/fundamentals path through the map; fixtures do not move."""
    text = match.group()
    if text in TESTS:
        return TESTS[text]
    if strict and not text.startswith("tests/fundamentals/fixtures"):
        problems.append(f"{where}: unmapped test path: {text}")
    return text


def map_config_text(match: re.Match[str], strict: bool, where: str) -> str:
    """A config path through the map; a new path stays; anything else needs a row."""
    text = match.group()
    rest = text.removeprefix("config/")
    top = rest.split("/")[0]
    if not rest or top in NEW_TOPS:
        return text
    prefix = config_prefix(top)
    if prefix is not None:
        return f"config/{prefix}/{rest}"
    if strict:
        problems.append(f"{where}: config path with no row: {text}")
    return text


def rewrite_text(value: str, strict: bool, where: str) -> str:
    """Every mapped module name and path inside one string."""
    if value in REL:
        return REL[value]
    for pattern, mapper in (
        (DOTTED, map_module_text),
        (SRC_PATH, map_src_text),
        (TEST_PATH, map_test_text),
        (CONFIG_PATH, map_config_text),
    ):
        value = pattern.sub(lambda m, mapper=mapper: mapper(m, strict, where), value)
    return value


def path_segment_allowed(old: str, new: str) -> bool:
    """Whether a folded path literal changed only by the rules the rewriter applies to paths."""
    if old == "fixtures" or old.startswith("fixtures/"):
        return new == f"tests/fundamentals/{old}"
    if old == "src/fundamentals":
        return new == "equity_os"
    if old.startswith("src/fundamentals/"):
        return new == MOVED.get(old)
    if old.startswith("config/"):
        rest = old.removeprefix("config/")
        return new == f"config/{config_prefix(rest.split('/')[0])}/{rest}"
    if old.startswith("tests/fundamentals/"):
        return new == TESTS.get(old)
    return new == f"{config_prefix(old.split('/')[0])}/{old}" or new == REL.get(old)


def allowed(old: str, new: str) -> bool:
    """Whether a string constant's change is one the map explains."""
    return rewrite_text(old, False, "") == new or path_segment_allowed(old, new)


class Offsets:
    """AST positions to byte offsets of one source."""

    def __init__(self, data: bytes) -> None:
        self.starts = [0]
        for index, byte in enumerate(data):
            if byte == 10:
                self.starts.append(index + 1)

    def span(self, node: ast.AST) -> tuple[int, int]:
        """The byte range of a node."""
        return (
            self.starts[node.lineno - 1] + node.col_offset,
            self.starts[node.end_lineno - 1] + node.end_col_offset,
        )


def target_of(module: str, name: str) -> tuple[str, str]:
    """Where ``from module import name`` now resolves: (new module, new name)."""
    if module in MOD:
        return MOD[module], name
    submodule = f"{module}.{name}"
    if submodule in MOD:
        package, _, leaf = MOD[submodule].rpartition(".")
        return package, leaf
    if module in KEPT_PACKAGES:
        return KEPT_PACKAGES[module], name
    if module in PACKAGES:
        return defining_module(module, name), name
    raise SystemExit(f"cannot resolve from {module} import {name}")


def defining_module(package: str, name: str) -> str:
    """The moved module a dropped package __init__ re-exported ``name`` from."""
    init = "src/" + package.replace(".", "/") + "/__init__.py"
    for node in ast.walk(ast.parse(run("git", "show", f"HEAD:{init}"))):
        if isinstance(node, ast.ImportFrom) and any(a.name == name for a in node.names):
            return MOD[node.module or ""]
    raise SystemExit(f"{package} does not re-export {name}")


def rewrite_import(
    node: ast.Import | ast.ImportFrom, data: bytes, offsets: Offsets, old_path: str, new_path: str
) -> tuple[int, int, bytes] | None:
    """The replacement for one import statement, or None when it is untouched."""
    start, end = offsets.span(node)
    text = data[start:end].decode()
    indent = " " * node.col_offset
    if isinstance(node, ast.Import):
        if not any(a.name.split(".")[0] == "fundamentals" for a in node.names):
            return None
        for alias in node.names:
            if alias.name not in MOD or alias.asname is None:
                raise SystemExit(f"{old_path}:{node.lineno}: unhandled import {alias.name}")
            text = text.replace(alias.name, MOD[alias.name])
        return start, end, text.encode()
    if node.level:
        module = node.module or ""
        beside = f"{old_path.rpartition('/')[0]}/{module}.py"
        if beside not in TESTS:
            raise SystemExit(f"{old_path}:{node.lineno}: unresolved relative import")
        moved_to = TESTS[beside]
        if (
            "/support/" not in moved_to
            and moved_to.rpartition("/")[0] == new_path.rpartition("/")[0]
        ):
            return None
        return start, end, re.sub(r"from\s+\.+", "from ", text, count=1).encode()
    module = node.module or ""
    if module.startswith("tests.fundamentals."):
        new = dotted(TESTS[module.replace(".", "/") + ".py"])
        return (
            start,
            end,
            re.sub(r"from\s+" + re.escape(module), f"from {new}", text, count=1).encode(),
        )
    if module.split(".")[0] != "fundamentals":
        return None
    targets = [(alias, target_of(module, alias.name)) for alias in node.names]
    if {target for _, (target, _) in targets} == {targets[0][1][0]} and all(
        alias.name == name for alias, (_, name) in targets
    ):
        new, count = re.subn(
            r"from\s+" + re.escape(module) + r"\s+import", f"from {targets[0][1][0]} import", text
        )
        assert count == 1, text
        return start, end, new.encode()
    if "#" in text:
        problems.append(f"{old_path}:{node.lineno}: a comment inside a split import needs a row")
        return None
    lines = []
    for alias, (target, name) in targets:
        local = alias.asname or alias.name
        suffix = "" if local == name else f" as {local}"
        lines.append(f"from {target} import {name}{suffix}")
    return start, end, ("\n" + indent).join(lines).encode()


def path_root(node: ast.AST) -> ast.AST:
    """The object a chain of attributes, subscripts and calls hangs from."""
    while True:
        if isinstance(node, ast.Attribute | ast.Subscript):
            node = node.value
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            node = node.func.value
        else:
            return node


def is_file_path(node: ast.AST) -> bool:
    """``Path(__file__)``."""
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "Path"
        and len(node.args) == 1
        and isinstance(node.args[0], ast.Name)
        and node.args[0].id == "__file__"
    )


def is_string(node: ast.AST) -> bool:
    """A plain string constant."""
    return isinstance(node, ast.Constant) and isinstance(node.value, str)


def is_config_literal(node: ast.AST) -> bool:
    """``"config"`` or ``Path("config")``."""
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "Path":
        return len(node.args) == 1 and is_config_literal(node.args[0])
    return is_string(node) and node.value == "config"


def is_config_root(node: ast.AST) -> bool:
    """A config literal or a name the code uses for the config root."""
    return (
        is_config_literal(node)
        or (isinstance(node, ast.Name) and node.id in CONFIG_ROOT_NAMES)
        or (isinstance(node, ast.Attribute) and node.attr in CONFIG_ROOT_NAMES)
    )


def flatten(node: ast.BinOp) -> tuple[ast.AST, list[ast.AST]]:
    """A ``/`` chain as (root, segments), left to right."""
    parts: list[ast.AST] = []
    current: ast.AST = node
    while isinstance(current, ast.BinOp) and isinstance(current.op, ast.Div):
        parts.append(current.right)
        current = current.left
    return current, parts[::-1]


class Rewriter:
    """Every byte replacement for one Python file."""

    def __init__(self, data: bytes, old_path: str, new_path: str, keep: set[str]) -> None:
        self.data, self.old_path, self.new_path, self.keep = data, old_path, new_path, keep
        self.offsets = Offsets(data)
        self.edits: list[tuple[int, int, bytes]] = []
        self.handled: set[int] = set()

    def literal(self, node: ast.AST, value: str) -> None:
        """Replace a whole constant by a new double-quoted literal."""
        start, end = self.offsets.span(node)
        self.edits.append((start, end, json.dumps(value).encode()))

    def insert_prefix(self, node: ast.AST, prefix: str) -> None:
        """Put a path prefix inside a constant or at the head of an f-string."""
        start, _ = self.offsets.span(node)
        quote = self.data[start : start + 2]
        at = start + (2 if quote[:1] in (b"f", b"F") else 1)
        self.edits.append((at, at, f"{prefix}/".encode()))

    def chain(self, node: ast.BinOp) -> None:
        """Rewrite the path literals of one outermost ``/`` chain."""
        root, parts = flatten(node)
        items = [root, *parts]
        rooted_in_tmp = "tmp" in self.data[slice(*self.offsets.span(root))].decode()
        index = 0
        while index < len(items):
            item = items[index]
            if not is_string(item):
                index += 1
                continue
            run_end = index
            while run_end + 1 < len(items) and is_string(items[run_end + 1]):
                run_end += 1
            run_items = items[index : run_end + 1]
            self.run(run_items, items[index - 1] if index else None, items, run_end, rooted_in_tmp)
            index = run_end + 1
        self.after_config_fstring(items)

    def after_config_fstring(self, items: list[ast.AST]) -> None:
        """``"config" / f"aparinds-{quarter}.yaml"``: the name prefix decides the bucket."""
        for before, item in zip(items, items[1:], strict=False):
            if is_config_root(before) and isinstance(item, ast.JoinedStr):
                head = item.values[0]
                if is_string(head) and config_prefix(head.value.split("/")[0]):
                    self.insert_prefix(item, config_prefix(head.value.split("/")[0]) or "")
                    self.handled.update(id(value) for value in item.values)

    def run(
        self,
        run_items: list[ast.AST],
        before: ast.AST | None,
        items: list[ast.AST],
        run_end: int,
        rooted_in_tmp: bool,
    ) -> None:
        """One run of consecutive string segments."""
        joined = "/".join(item.value for item in run_items)
        first, last = run_items[0], run_items[-1]
        whole = (self.offsets.span(first)[0], self.offsets.span(last)[1])
        if len(run_items) == 1 and first is items[0] and joined != "config":
            return
        if joined.split("/")[:2] == ["src", "fundamentals"]:
            mapped = "equity_os" if joined == "src/fundamentals" else MOVED.get(joined)
            if mapped is None:
                problems.append(f"{self.old_path}:{first.lineno}: source path: {joined}")
            else:
                self.edits.append((*whole, json.dumps(mapped).encode()))
            self.handled.update(id(item) for item in run_items)
        elif joined.split("/")[:2] == ["tests", "fundamentals"]:
            if joined.startswith("tests/fundamentals/fixtures"):
                pass
            elif joined in TESTS:
                self.edits.append((*whole, json.dumps(TESTS[joined]).encode()))
            else:
                problems.append(f"{self.old_path}:{first.lineno}: test path: {joined}")
            self.handled.update(id(item) for item in run_items)
        elif joined in REL:
            self.edits.append((*whole, json.dumps(REL[joined]).encode()))
            self.handled.update(id(item) for item in run_items)
        elif first.value == "config":
            self.handled.add(id(first))
            if len(run_items) > 1:
                self.config_tail(run_items[1], rooted_in_tmp)
        elif before is not None and is_string(first):
            top = first.value.split("/")[0]
            if top in DIR_TOPS or is_config_root(before):
                self.config_tail(first, rooted_in_tmp)

    def config_tail(self, segment: ast.AST, rooted_in_tmp: bool) -> None:
        """The first segment under a config root gains its bucket."""
        top = segment.value.split("/")[0]
        if top in self.keep or top in NEW_TOPS:
            return
        prefix = config_prefix(top)
        if prefix is None or (rooted_in_tmp and "." in top):
            self.handled.add(id(segment))
            return
        self.insert_prefix(segment, prefix)
        self.handled.add(id(segment))

    def anchor(self, node: ast.BinOp) -> None:
        """``Path(__file__).parent / "fixtures"`` becomes repo-rooted."""
        left, right = node.left, node.right
        if not (
            isinstance(left, ast.Attribute)
            and left.attr == "parent"
            and is_string(right)
            and right.value == "fixtures"
            and self.file_rooted(left.value)
        ):
            return
        depth = len(PurePosixPath(self.new_path).parents) - 1
        end = self.offsets.span(left)[1]
        self.edits.append((end - len(".parent"), end, f".parents[{depth}]".encode()))
        self.literal(right, "tests/fundamentals/fixtures")
        self.handled.add(id(right))

    def file_rooted(self, node: ast.AST) -> bool:
        """``Path(__file__)`` or ``Path(__file__).resolve()``."""
        if is_file_path(node):
            return True
        return (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "resolve"
            and is_file_path(node.func.value)
        )

    def parents(self, node: ast.Subscript) -> None:
        """``parents[n]`` reaches the same directory from the new location."""
        target = node.value
        if not (
            isinstance(target, ast.Attribute)
            and target.attr == "parents"
            and self.file_rooted(target.value)
            and isinstance(node.slice, ast.Constant)
        ):
            return
        old, new = PurePosixPath(self.old_path), PurePosixPath(self.new_path)
        reached = old.parents[node.slice.value]
        if str(reached) == "src/fundamentals":
            reached = PurePosixPath("equity_os")
        if reached not in new.parents:
            problems.append(f"{self.old_path}:{node.lineno}: parents[] target moved: {reached}")
            return
        depth = list(new.parents).index(reached)
        self.edits.append((*self.offsets.span(node.slice), str(depth).encode()))

    def strings(self, tree: ast.Module) -> None:
        """Every string constant the chains did not take."""
        documented = {id(node) for node in documented_nodes(tree)}
        loggers = set()
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in ("get_logger", "getLogger")
            ):
                loggers.update(id(arg) for arg in node.args)
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.JoinedStr)
                and node.values
                and id(node.values[0]) not in self.handled
            ):
                head, tail = node.values[0], node.values[-1]
                named = is_string(head) and is_string(tail) and head.value not in self.keep
                if named and config_relative(head.value + tail.value):
                    problems.append(f"{self.old_path}:{node.lineno}: config f-string with no row")
            if not is_string(node) or id(node) in self.handled or id(node) in loggers:
                continue
            if node.value in self.keep:
                continue
            where = f"{self.old_path}:{node.lineno}"
            new = rewrite_text(node.value, id(node) not in documented, where)
            if new == node.value:
                if id(node) not in documented and config_relative(node.value):
                    problems.append(f"{where}: config-relative name with no row: {node.value}")
                continue
            start, end = self.offsets.span(node)
            raw = self.data[start:end]
            fragments = []
            for pattern in (DOTTED, SRC_PATH, TEST_PATH, CONFIG_PATH):
                fragments += [m.group() for m in pattern.finditer(node.value)]
            changed = [f for f in fragments if rewrite_text(f, False, "") != f]
            if node.value in REL or not changed:
                self.edits.append((start, end, json.dumps(new).encode()))
                continue
            for fragment in sorted(set(changed), key=len, reverse=True):
                replacement = rewrite_text(fragment, False, "").encode()
                if fragment.encode() not in raw:
                    problems.append(f"{where}: cannot place {fragment} in its literal")
                raw = re.sub(
                    rb"(?<![\w./-])" + re.escape(fragment.encode()) + rb"(?![\w/-])",
                    lambda _, r=replacement: r,
                    raw,
                )
            self.edits.append((start, end, raw))

    def result(self, pinned: bool) -> bytes:
        """The file after every replacement."""
        tree = ast.parse(self.data)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import | ast.ImportFrom):
                edit = rewrite_import(node, self.data, self.offsets, self.old_path, self.new_path)
                if edit:
                    self.edits.append(edit)
        if not pinned:
            inner = set()
            for node in ast.walk(tree):
                if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
                    inner.add(id(node.left))
            for node in ast.walk(tree):
                if isinstance(node, ast.Subscript):
                    self.parents(node)
                if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
                    self.anchor(node)
                    if id(node) not in inner:
                        self.chain(node)
            self.strings(tree)
        data = self.data
        for start, end, new in sorted(self.edits, key=lambda e: (e[0], e[1]), reverse=True):
            data = data[:start] + new + data[end:]
        return data


def documented_nodes(tree: ast.Module) -> list[ast.Constant]:
    """Every docstring of a module."""
    return [
        node.body[0].value
        for node in ast.walk(tree)
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef)
        and node.body
        and isinstance(node.body[0], ast.Expr)
        and is_string(node.body[0].value)
    ]


def wrap_docstrings(text: str) -> str:
    """A docstring line a longer path pushed past the limit breaks at its last fitting space."""
    lines = text.split("\n")
    spans = [(node.lineno, node.end_lineno) for node in documented_nodes(ast.parse(text))]
    for first, last in sorted(spans, reverse=True):
        for number in range(last, first - 1, -1):
            line = lines[number - 1]
            if len(line.encode()) > LINE_LIMIT:
                indent = line[: len(line) - len(line.lstrip())]
                cut = line.rfind(" ", len(indent) + 1, LINE_LIMIT)
                if cut < 0:
                    continue
                lines[number - 1 : number] = [line[:cut], indent + line[cut + 1 :]]
    return "\n".join(lines)


def unescape(text: str) -> str:
    """edits.tsv's two escapes."""
    return text.replace("\\n", "\n").replace("\\t", "\t")


def load_edits() -> tuple[dict[str, list[dict[str, str]]], dict[str, set[str]]]:
    """edits.tsv by old path: the real edits, and the literals kept as they are."""
    edits: dict[str, list[dict[str, str]]] = {}
    keep: dict[str, set[str]] = {}
    for row in read_tsv("edits.tsv"):
        if row["old_text"] == row["new_text"]:
            keep.setdefault(row["path"], set()).add(unescape(row["old_text"]))
        else:
            edits.setdefault(row["path"], []).append(row)
    pinned_rows = [path for path in edits if path in PINNED_OLD]
    for path in pinned_rows:
        if len(edits[path]) != 1 or "_OUTCOME_KIND" not in edits[path][0]["old_text"]:
            raise SystemExit(
                f"REFUSED: a pinned file may hold only its wire-identifier row: {path}"
            )
    if len(pinned_rows) > 2:
        raise SystemExit(f"REFUSED: more than two pinned-file rows: {pinned_rows}")
    return edits, keep


def apply_edits(text: str, path: str, rows: list[dict[str, str]]) -> str:
    """The deliberate edits to one file; each must match its stated count."""
    for row in rows:
        old, new = unescape(row["old_text"]), unescape(row["new_text"])
        if text.count(old) != int(row["count"]):
            problems.append(f"{path}: edit matched {text.count(old)}, not {row['count']}: {old!r}")
        text = text.replace(old, new)
    return text


class Normal(ast.NodeTransformer):
    """A tree with imports gone, ``/`` chains folded and ``Path(__file__)`` anchors masked."""

    def visit_Import(self, node: ast.Import) -> None:
        return None

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        return None

    def anchored(self, node: ast.AST) -> bool:
        """A chain of attributes, subscripts and calls on ``Path(__file__)``."""
        while isinstance(node, ast.Attribute | ast.Subscript | ast.Call):
            if is_file_path(node):
                return True
            node = node.func if isinstance(node, ast.Call) else node.value
        return False

    def visit_Call(self, node: ast.Call) -> ast.AST:
        if self.anchored(node):
            return ast.Name(id="__ANCHOR__", ctx=ast.Load())
        return self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> ast.AST:
        if node.attr in ("parent", "parents", "resolve") and self.anchored(node):
            return ast.Name(id="__ANCHOR__", ctx=ast.Load())
        return self.generic_visit(node)

    def visit_Subscript(self, node: ast.Subscript) -> ast.AST:
        if isinstance(node.value, ast.Attribute) and node.value.attr == "parents":
            if self.anchored(node.value):
                return ast.Name(id="__ANCHOR__", ctx=ast.Load())
        return self.generic_visit(node)

    def visit_BinOp(self, node: ast.BinOp) -> ast.AST:
        self.generic_visit(node)
        if not (isinstance(node.op, ast.Div) and is_string(node.right)):
            return node
        if is_string(node.left):
            return ast.Constant(value=f"{node.left.value}/{node.right.value}")
        left = node.left
        if isinstance(left, ast.BinOp) and isinstance(left.op, ast.Div) and is_string(left.right):
            left.right = ast.Constant(value=f"{left.right.value}/{node.right.value}")
            return left
        return node


def difference(old: ast.AST, new: ast.AST, path: str, line: int = 0) -> str | None:
    """The first difference the map does not explain, or None."""
    line = getattr(old, "lineno", line)
    if not isinstance(old, ast.AST) and old == new:
        return None
    if type(old) is not type(new) or not isinstance(old, ast.AST):
        return f"{path}:{line}: {type(old).__name__} became {type(new).__name__}"
    if isinstance(old, ast.Constant):
        if old.value == new.value:
            return None
        if isinstance(old.value, str) and isinstance(new.value, str):
            if allowed(old.value, new.value):
                return None
        return f"{path}:{line}: {old.value!r} became {new.value!r}"
    for field in old._fields:
        left, right = getattr(old, field, None), getattr(new, field, None)
        if isinstance(left, list):
            if not isinstance(right, list) or len(left) != len(right):
                return f"{path}:{line}: {field} length changed"
            for one, other in zip(left, right, strict=True):
                found = difference(one, other, path, line)
                if found:
                    return found
        elif isinstance(left, ast.AST):
            found = difference(left, right, path, line)
            if found:
                return found
        elif left != right:
            return f"{path}:{line}: {field} {left!r} became {right!r}"
    return None


def bindings(tree: ast.Module, old_side: bool) -> Counter[tuple[str, str, str, str]]:
    """Every (scope, local name, module, attribute) an import binds, in new-tree terms."""
    found: Counter[tuple[str, str, str, str]] = Counter()

    def canonical(module: str, name: str) -> tuple[str, str]:
        if f"{module}.{name}" in NEW_MODULES:
            return f"{module}.{name}", ""
        return module, name

    def visit(node: ast.AST, scope: str) -> None:
        for child in ast.iter_child_nodes(node):
            inner = scope
            if isinstance(child, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
                inner = f"{scope}.{child.name}"
            if isinstance(child, ast.Import):
                for alias in child.names:
                    module = MOD.get(alias.name, alias.name) if old_side else alias.name
                    local = alias.asname or alias.name.split(".")[0]
                    found[(scope, local, module, "")] += 1
            elif isinstance(child, ast.ImportFrom):
                module = child.module or ""
                for alias in child.names:
                    name = alias.name
                    if old_side and module.startswith("tests.fundamentals."):
                        module_new = dotted(TESTS[module.replace(".", "/") + ".py"])
                    elif old_side and not child.level and module.split(".")[0] == "fundamentals":
                        module_new, name = target_of(module, name)
                    elif child.level and old_side and f"tests/fundamentals/{module}.py" in TESTS:
                        module_new = module
                    else:
                        module_new = module
                    found[(scope, alias.asname or alias.name, *canonical(module_new, name))] += 1
            visit(child, inner)

    visit(tree, "")
    return found


def strip_imports(text: str) -> list[str]:
    """A pinned file's lines with its import statements and blank lines gone."""
    tree = ast.parse(text)
    drop = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import | ast.ImportFrom):
            drop.update(range(node.lineno, node.end_lineno + 1))
    lines = text.splitlines()
    return [line for number, line in enumerate(lines, 1) if number not in drop and line.strip()]


def prove(expected_old: dict[str, str]) -> None:
    """The logic-free proof over every moved Python file, against the edited old text."""
    for old_path, old_text in expected_old.items():
        new_path = MOVED.get(old_path, old_path)
        new_text = Path(new_path).read_text()
        if new_path.endswith("run_config.py"):
            new_text = re.sub(
                r"MOVED_PINS: Mapping\[str, str\] = \{.*?^\}\n",
                MOVED_PINS_PLACEHOLDER + "\n",
                new_text,
                flags=re.S | re.M,
            )
        old_tree, new_tree = ast.parse(old_text), ast.parse(new_text)
        if old_path not in PINNED_OLD:
            for node in (*documented_nodes(old_tree), *documented_nodes(new_tree)):
                node.value = " ".join(node.value.split())
        if bindings(old_tree, True) != bindings(new_tree, False):
            delta = bindings(old_tree, True) - bindings(new_tree, False)
            problems.append(f"PROOF {old_path}: import bindings differ: {list(delta)[:3]}")
        if old_path in PINNED_OLD:
            if strip_imports(old_text) != strip_imports(new_text):
                problems.append(f"PROOF {old_path}: a pinned file differs outside its imports")
            continue
        found = difference(Normal().visit(old_tree), Normal().visit(new_tree), old_path)
        if found:
            problems.append(f"PROOF {found}")


PINS_SNIPPET = """
import json, sys
from {run_config} import extractor_pin, vendor_extractor_pin
from {canonical} import Representation
wanted = json.loads(sys.argv[1])
out = {{}}
for artifact, version in wanted:
    if artifact.startswith("extractor_"):
        kind = Representation[artifact.removeprefix("extractor_").upper()]
        pin = extractor_pin(kind, version=version)
    else:
        pin = vendor_extractor_pin(artifact.split(":", 1)[1], "-", version=version)
    out[artifact] = pin.content_sha256
print(json.dumps(out))
"""


def computed_pins(run_config: str, canonical: str, wanted: list[list[str]]) -> dict[str, str]:
    """The five pins as the given tree's own code computes them."""
    snippet = PINS_SNIPPET.format(run_config=run_config, canonical=canonical)
    output = run("uv", "run", "python", "-c", snippet, json.dumps(wanted))
    return dict(json.loads(output.strip().splitlines()[-1]))


SOURCES_SNIPPET = """
import json
from {run_config} import EXTRACTOR_SOURCES, SHP_EXTRACTOR_SOURCES, VENDOR_EXTRACTORS
lists = [*EXTRACTOR_SOURCES.values(), SHP_EXTRACTOR_SOURCES]
lists += [sources for _, sources in VENDOR_EXTRACTORS.values()]
print(json.dumps([list(item) for item in lists]))
"""


def source_lists(run_config: str) -> list[list[str]]:
    """Every extractor's ordered source list, as that tree's own code states it."""
    output = run("uv", "run", "python", "-c", SOURCES_SNIPPET.format(run_config=run_config))
    return list(json.loads(output.strip().splitlines()[-1]))


def digests(root: str, out: str) -> None:
    """Run capture_digests.py under one import root."""
    run("uv", "run", "python", str(HERE / "capture_digests.py"), root, out)


def write_pythonpath() -> None:
    """Every test folder on pytest's path: test modules import each other and support by bare name.

    Listed from every test row, present or not, so a replayed tree generates the same list.
    """
    folders = sorted(
        {row["new"].rpartition("/")[0] for row in read_tsv("moves.tsv") if row["kind"] == "test"}
    )
    listed = "".join(f'    "{folder}",\n' for folder in folders)
    project = Path("pyproject.toml")
    text = project.read_text()
    if text.count(PYTHONPATH_PLACEHOLDER) != 1:
        raise SystemExit("pyproject.toml has no pythonpath placeholder")
    project.write_text(text.replace(PYTHONPATH_PLACEHOLDER, f'pythonpath = [\n    ".",\n{listed}]'))


def write_support() -> None:
    """The one shared test helper the guards and frozen-manifest readers need."""
    table = {
        package: tuple(
            sorted(new for old, new in MOD.items() if old.startswith(f"fundamentals.{package}."))
        )
        for package in GUARDED_PACKAGES
    }
    rows = "\n".join(
        f'    "{package}": (\n' + "".join(f'        "{name}",\n' for name in names) + "    ),"
        for package, names in table.items()
    )
    prefixes = "\n".join(
        f'    "{top}": "{prefix}",'
        for top, prefix in sorted(PREFIX.items())
        if not top.startswith("aparinds-")
    )
    Path(SUPPORT).parent.mkdir(parents=True, exist_ok=True)
    Path(SUPPORT).write_text(
        '"""What the RESTRUCTURE-1 move recorded for test readers: old packages and config paths."""'
        "\n\nfrom pathlib import Path\n\n"
        "# Every module an old package held; a guard naming the package covers exactly these.\n"
        f"OLD_PACKAGES = {{\n{rows}\n}}\n"
        "# Frozen manifests record config paths as they were when frozen.\n"
        f"CONFIG_PREFIXES = {{\n{prefixes}\n}}\n\n\n"
        "def recorded_path(repo: Path, path: str) -> Path:\n"
        '    """A path a frozen manifest recorded: as written, or under its bucket after the move."""\n'
        "    written = repo / path\n"
        '    if written.exists() or not path.startswith("config/"):\n'
        "        return written\n"
        '    rest = path.removeprefix("config/")\n'
        '    top = rest.split("/")[0]\n'
        '    bucket = "runs" if top.startswith("aparinds-") else CONFIG_PREFIXES[top]\n'
        '    return repo / "config" / bucket / rest\n'
        "\n\n"
        "def old_package_files(package: str) -> list[Path]:\n"
        '    """The source files of the modules an old package held."""\n'
        "    repo = Path(__file__).resolve().parents[3]\n"
        '    return [repo / (name.replace(".", "/") + ".py") for name in OLD_PACKAGES[package]]\n'
    )


def main() -> None:
    """Refuse a dirty tree, move, rewrite, prove, commit."""
    if run("git", "status", "--porcelain"):
        raise SystemExit("REFUSED: the tree is dirty")
    pre_move = run("git", "rev-parse", "HEAD").strip()
    edits, keep = load_edits()
    live = read_tsv("live_pins.tsv")
    wanted = [[row["artifact"], row["version"]] for row in live]
    stored = {row["artifact"]: row["content_sha256"] for row in live}
    old_run_config = "fundamentals.compare.run_config"
    old_canonical = "fundamentals.contracts.canonical"
    legacy = computed_pins(old_run_config, old_canonical, wanted)
    if legacy != stored:
        raise SystemExit(f"legacy digests differ from the recorded live rows: {legacy} != {stored}")
    old_sources = source_lists(old_run_config)
    listed = {"src/fundamentals/" + name for item in old_sources for name in item}
    if listed != PINNED_OLD:
        raise SystemExit(f"pinned_files.txt differs from the source lists: {listed ^ PINNED_OLD}")
    Path("scratchpad/restructure").mkdir(parents=True, exist_ok=True)
    digests("fundamentals", "scratchpad/restructure/digests-before.json")

    python_rows = [row for row in MOVES if row["old"].endswith(".py") and row["old"] in MOVED]
    expected_old: dict[str, str] = {}
    for row in python_rows:
        path = row["old"]
        expected_old[path] = apply_edits(Path(path).read_text(), path, edits.pop(path, []))
    for path in PY_SCRIPTS:
        expected_old[path] = apply_edits(Path(path).read_text(), path, edits.pop(path, []))
    text_files = {}
    for path in (*TEXT_SCRIPTS, *edits):
        text_files[path] = apply_edits(Path(path).read_text(), path, edits.get(path, []))
    for path in DELETED_INITS:
        run("git", "rm", "-q", "--", path)
    for old, new in MOVED.items():
        Path(new).parent.mkdir(parents=True, exist_ok=True)
        run("git", "mv", "--", old, new)

    changed: list[str] = list(MOVED.values())
    for old, text in expected_old.items():
        new = MOVED.get(old, old)
        rewriter = Rewriter(text.encode(), old, new, keep.get(old, set()))
        result = rewriter.result(old in PINNED_OLD).decode()
        Path(new).write_text(result if old in PINNED_OLD else wrap_docstrings(result))
    for path, text in text_files.items():
        out = rewrite_text(text, False, path) if path in TEXT_SCRIPTS else text
        Path(path).write_text(out)

    inits = {
        str(parent)
        for row in MOVES
        if row["kind"] == "module"
        for parent in PurePosixPath(row["new"]).parents
        if str(parent) != "."
    }
    for directory in sorted(inits):
        init = Path(directory, "__init__.py")
        if not init.exists():
            init.write_text(f'"""{directory.replace("/", ".")} package."""\n')
            changed.append(str(init))
    write_support()
    changed.append(SUPPORT)
    write_pythonpath()
    if problems:
        print("\n".join(sorted(set(problems))))
        raise SystemExit(f"{len(set(problems))} unresolved")

    run("uv", "lock")
    python_changed = [p for p in [*changed, *PY_SCRIPTS] if p.endswith(".py")]
    run("uv", "run", "ruff", "check", "--select", "I", "--fix", "-q", *python_changed)
    run("uv", "run", "ruff", "format", "-q", *python_changed)

    new_run_config = MOD[old_run_config]
    if source_lists(new_run_config) != [[REL[name] for name in item] for item in old_sources]:
        raise SystemExit("an extractor's source list is not its old list through the map")
    moved_pins = computed_pins(new_run_config, MOD[old_canonical], wanted)
    table = "".join(
        f'    "{moved_pins[artifact]}": "{stored[artifact]}",  # noqa: E501\n'
        for artifact in stored
    )
    config_file = Path(MOVED["src/fundamentals/compare/run_config.py"])
    source = config_file.read_text()
    if source.count(MOVED_PINS_PLACEHOLDER) != 1:
        raise SystemExit("run_config.py has no MOVED_PINS placeholder")
    config_file.write_text(
        source.replace(
            MOVED_PINS_PLACEHOLDER,
            f"# Digest of each moved source set -> the digest already stored for it.\n"
            f"MOVED_PINS: Mapping[str, str] = {{\n{table}}}\n",
        )
    )
    if computed_pins(new_run_config, MOD[old_canonical], wanted) != stored:
        raise SystemExit("the bridge does not reproduce the stored pins")
    digests("equity_os", "scratchpad/restructure/digests-after.json")
    before = Path("scratchpad/restructure/digests-before.json").read_text()
    if before != Path("scratchpad/restructure/digests-after.json").read_text():
        raise SystemExit("parser digests changed")

    prove(expected_old)
    if problems:
        print("\n".join(sorted(set(problems))))
        raise SystemExit(f"{len(set(problems))} proof failures")
    run("git", "add", "--", *changed, *PY_SCRIPTS, *text_files, "uv.lock")
    message = (
        "refactor(restructure): move source, config and tests into buckets (eqos-foec)\n\n"
        f"Written only by scripts/restructure/move.py from the pre-move tip P {pre_move}.\n"
        "The logic-free proof passed; every exception is a row in edits.tsv.\n\n"
        "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n"
    )
    run("git", "commit", "-q", "-m", message)
    print("MOVE OK", run("git", "rev-parse", "HEAD").strip(), "from", pre_move)


